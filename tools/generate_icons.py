"""Generate native-size anti-aliased RGBA sprites and matching browser vectors.

Install: python -m pip install -r tools/icon-requirements.txt
Run: python tools/generate_icons.py
The firmware build only needs the committed generated header, not Python.
"""
from pathlib import Path
import io,json,re
import resvg_py
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
NAMES=['sun','book','waves','candle','meeting','heart','focus','show']
SIZE=64
images=[];vectors=[]
for name in NAMES:
    svg=(ROOT/'assets/icons'/f'{name}.svg').read_text(encoding='utf-8')
    vectors.append(svg[svg.index('>')+1:svg.rindex('</svg>')])
    png=resvg_py.svg_to_bytes(svg_string=svg,width=SIZE*8,height=SIZE*8,skip_system_fonts=True)
    image=Image.open(io.BytesIO(png)).convert('RGBA').resize((SIZE,SIZE),Image.Resampling.LANCZOS)
    assert image.getbbox() and any(0<a<255 for *_,a in image.get_flattened_data()), 'Missing antialiasing'
    images.append(image)

lines=['// Generated by tools/generate_icons.py; edit assets/icons/*.svg instead.',
       '#pragma once','#include <Arduino.h>',
       f'constexpr uint8_t SCENE_ICON_SIZE = {SIZE};',
       f'constexpr uint8_t SCENE_ICON_COUNT = {len(images)};',
       f'static const uint32_t SCENE_ICON_RGBA[{len(images)}][{SIZE*SIZE}] PROGMEM = {{']
for name,image in zip(NAMES,images):
    lines.append('    { // '+name)
    pixels=[(a<<24)|(r<<16)|(g<<8)|b for r,g,b,a in image.get_flattened_data()]
    for index in range(0,len(pixels),8):
        lines.append('        '+','.join(f'0x{pixel:08x}' for pixel in pixels[index:index+8])+',')
    lines.append('    },')
lines.append('};\n')
(ROOT/'src/cyd/scene_icon_assets.h').write_text('\n'.join(lines),encoding='utf-8')
path=ROOT/'src/cyd/web_ui.h';web=path.read_text(encoding='utf-8')
web=re.sub(r'const richIcons=\[.*?\n\];',lambda _: 'const richIcons='+json.dumps(vectors,ensure_ascii=False,indent=0)+';',web,flags=re.S)
web=web.replace("n.setAttribute('viewBox','0 0 48 48')","n.setAttribute('viewBox','-6 -6 60 60')")
path.write_text(web,encoding='utf-8')
print(f'Generated {len(images)} RGBA icons, {SIZE}x{SIZE}, {len(images)*SIZE*SIZE*4:,} flash bytes')
